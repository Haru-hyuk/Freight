function cloneDetail(detail: QuoteDetailResponse): QuoteDetailResponse {
  return {
    ...detail,
    checklistItems: Array.isArray(detail.checklistItems) ? detail.checklistItems.map((item) => ({ ...item })) : [],
    stops: Array.isArray(detail.stops) ? detail.stops.map((stop) => ({ ...stop })) : [],
  };
}

function parseQuoteIdFromIdentifier(identifier: string): number {
  const raw = String(identifier ?? "").trim();
  if (!raw) return 0;

  const numeric = Number(raw);
  if (Number.isInteger(numeric) && numeric > 0) return numeric;

  const match = /^mock-quote-(\d+)$/i.exec(raw);
  if (!match) return 0;

  const parsed = Number(match[1]);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : 0;
}

export function getMockShipperQuoteDetailByCase(quoteId: number): QuoteDetailResponse | null {
  const safeId = Number.isInteger(quoteId) && quoteId > 0 ? quoteId : 0;
  if (safeId <= 0) return null;
  const detail = MOCK_SHIPPER_QUOTE_DETAIL_BY_ID[safeId];
  return detail ? cloneDetail(detail) : null;
}

export function getMockShipperQuoteDetailByIdentifierByCase(quoteIdentifier: string): QuoteDetailResponse | null {
  const quoteId = parseQuoteIdFromIdentifier(quoteIdentifier);
  if (quoteId <= 0) return null;
  return getMockShipperQuoteDetailByCase(quoteId);
}
